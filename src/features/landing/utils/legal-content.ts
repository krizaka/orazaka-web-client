/** A legal text in both languages; its sections are named so each one is told apart, and drawn in the order written. */
function legal(
  words: { sections: Record<string, { title: Word; text: Word }> } & Record<
    string,
    unknown
  >,
): Record<Locale, LegalContent> {
  const read = (index: 0 | 1): LegalContent => {
    const { sections, ...rest } = words;
    return {
      ...(localise(rest, index) as Omit<LegalContent, "sections">),
      sections: Object.values(sections).map((section) =>
        localise(section, index),
      ),
    };
  };
  return { en: read(0), fr: read(1) };
}

